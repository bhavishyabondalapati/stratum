"""Measure line coverage of the test suite using only the standard library.

    python coverage_report.py            # print the table
    python coverage_report.py --write    # also write COVERAGE.md

How it works: ``sys.settrace`` lets us install a hook that the interpreter
calls for every line it executes (the stdlib ``trace`` module is built on
the same hook). We record every (file, line) inside the ``stratum``
package while the whole unittest suite runs, then for each source file
compare the lines that ran against the lines that *could* run (taken from
the compiled bytecode).

Why not ``trace.Trace`` directly? It caches its "ignore this module"
decision by bare module name, so our ``stratum/__init__.py`` is confused
with the standard library's many ``__init__.py`` files and reported as
never executed. A 15-line hook of our own avoids that and is faster.

Limits: code that only runs in a child process (the crash-test worker, the
`python -m stratum.server` process) is not seen by the hook, so the real
coverage is slightly higher than reported. Tracing is slow, so the
randomized tests run in a reduced "quick" mode here.
"""

import os
import sys
import threading
import unittest

ROOT = os.path.dirname(os.path.abspath(__file__))
PACKAGE = os.path.join(ROOT, "stratum")


def executable_lines(path):
    """Line numbers that hold executable code, found by walking the
    compiled code objects (functions nested inside the module)."""
    with open(path, "rb") as f:
        code = compile(f.read(), path, "exec")
    lines = set()
    stack = [code]
    while stack:
        current = stack.pop()
        for _, _, lineno in current.co_lines():
            if lineno:
                lines.add(lineno)
        for const in current.co_consts:
            if hasattr(const, "co_lines"):
                stack.append(const)
    lines.discard(0)  # line 0 is interpreter bookkeeping, not source
    return lines


def main():
    os.environ.setdefault("STRATUM_QUICK", "1")
    os.chdir(ROOT)
    sys.path.insert(0, ROOT)

    executed = {}  # absolute file path -> set of executed line numbers
    prefix = PACKAGE + os.sep

    def global_hook(frame, event, arg):
        """Called on every function call. Returning None means "do not
        trace inside this function", which keeps non-Stratum code fast."""
        filename = frame.f_code.co_filename
        if not filename.startswith(prefix):
            return None
        lines = executed.setdefault(filename, set())
        lines.add(frame.f_lineno)

        def local_hook(frame, event, arg):
            if event == "line":
                lines.add(frame.f_lineno)
            return local_hook

        return local_hook

    outcome = {}

    def run_suite():
        # Imports happen in here so module-level lines are traced too.
        suite = unittest.defaultTestLoader.discover("tests", top_level_dir=ROOT)
        outcome["result"] = unittest.TextTestRunner(verbosity=1).run(suite)

    threading.settrace(global_hook)  # threads started from now on
    sys.settrace(global_hook)  # this thread
    try:
        run_suite()
    finally:
        sys.settrace(None)
        threading.settrace(None)

    rows = []
    total_lines = total_hit = 0
    for name in sorted(os.listdir(PACKAGE)):
        if not name.endswith(".py"):
            continue
        path = os.path.join(PACKAGE, name)
        possible = executable_lines(path)
        hit = possible & executed.get(path, set())
        missing = sorted(possible - hit)
        rows.append((name, len(possible), len(hit), missing))
        total_lines += len(possible)
        total_hit += len(hit)

    def percent(hit, possible):
        return 100.0 * hit / possible if possible else 100.0

    print()
    print(f"{'file':<16}{'lines':>7}{'covered':>9}{'percent':>9}   missing")
    for name, possible, hit, missing in rows:
        shown = ", ".join(map(str, missing[:12])) + (" ..." if len(missing) > 12 else "")
        print(f"{name:<16}{possible:>7}{hit:>9}{percent(hit, possible):>8.1f}%   {shown}")
    print(f"{'TOTAL':<16}{total_lines:>7}{total_hit:>9}{percent(total_hit, total_lines):>8.1f}%")

    result = outcome["result"]
    if "--write" in sys.argv:
        with open(os.path.join(ROOT, "COVERAGE.md"), "w") as f:
            f.write("# Line coverage\n\n")
            f.write("Generated by `python coverage_report.py --write` "
                    "(stdlib `sys.settrace` hook, quick test mode).\n\n")
            f.write(f"Python {sys.version.split()[0]}, {result.testsRun} tests run.\n\n")
            f.write("| File | Executable lines | Covered | Coverage | Lines not covered |\n")
            f.write("|---|---:|---:|---:|---|\n")
            for name, possible, hit, missing in rows:
                f.write(f"| `stratum/{name}` | {possible} | {hit} | "
                        f"{percent(hit, possible):.1f}% | "
                        f"{', '.join(map(str, missing)) or '-'} |\n")
            f.write(f"| **Total** | **{total_lines}** | **{total_hit}** | "
                    f"**{percent(total_hit, total_lines):.1f}%** | |\n\n")
            f.write("Lines that only execute inside child processes (the SIGKILLed "
                    "crash worker and the `python -m stratum.server` process) are "
                    "not visible to the tracer, so they count as not covered here "
                    "even though the tests do exercise them.\n")
    return 0 if result.wasSuccessful() else 1


if __name__ == "__main__":
    sys.exit(main())
